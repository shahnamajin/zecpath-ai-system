from .screening_scorer import ScreeningScorer
from .score_aggregator import ScoreAggregator


class ScreeningScoringEngine:
    """
    Complete screening scoring engine.

    Takes structured answers generated by Day 25
    and produces explainable screening scores.
    """

    def __init__(self):

        self.scorer = ScreeningScorer()

        self.aggregator = ScoreAggregator()

    def generate_explanation(
        self,
        scores,
        intent,
        quality
    ):
        """
        Generate human-readable scoring explanations.
        """

        explanations = []

        if scores["clarity"] >= 80:
            explanations.append(
                "The candidate communicated the answer clearly."
            )
        elif scores["clarity"] >= 50:
            explanations.append(
                "The candidate provided a moderately clear answer."
            )
        else:
            explanations.append(
                "The answer lacked sufficient clarity."
            )

        if quality.get("is_off_topic"):
            explanations.append(
                "The response was not relevant to the screening question."
            )
        elif scores["relevance"] >= 80:
            explanations.append(
                "The response was relevant to the question."
            )

        if quality.get("is_missing"):
            explanations.append(
                "No meaningful answer was provided."
            )
        elif quality.get("is_vague"):
            explanations.append(
                "The answer was too vague to provide sufficient information."
            )
        elif scores["completeness"] >= 80:
            explanations.append(
                "The response contained sufficient information."
            )

        if scores["consistency"] >= 80:
            explanations.append(
                "The response was consistent with the available candidate information."
            )
        else:
            explanations.append(
                "The response may contain information that differs from previously provided details."
            )

        return explanations

    def score_question(
        self,
        candidate_id,
        job_id,
        question_id,
        question_category,
        answer_data,
        previous_context=None
    ):
        """
        Score one candidate answer.
        """

        text = answer_data.get(
            "answer",
            {}
        ).get(
            "raw_text",
            ""
        )

        intent = answer_data.get(
            "answer",
            {}
        ).get(
            "intent",
            "missing"
        )

        entities = answer_data.get(
            "entities",
            {}
        )

        quality = answer_data.get(
            "quality",
            {}
        )

        scores = self.scorer.score_answer(
            text=text,
            intent=intent,
            entities=entities,
            quality=quality,
            previous_context=previous_context
        )

        explanation = self.generate_explanation(
            scores,
            intent,
            quality
        )

        return {
            "candidate_id": candidate_id,
            "job_id": job_id,
            "question_id": question_id,
            "question_category": question_category,

            "scores": scores,

            "explanation": explanation
        }

    def calculate_final_score(
        self,
        candidate_id,
        job_id,
        question_results
    ):
        """
        Aggregate all per-question scores.
        """

        score_data = [
            result["scores"]
            for result in question_results
        ]

        aggregate = self.aggregator.aggregate(
            score_data
        )

        return {
            "candidate_id": candidate_id,
            "job_id": job_id,

            "question_scores": question_results,

            "final_screening_score": aggregate[
                "normalized_score"
            ],

            "score_summary": aggregate
        }